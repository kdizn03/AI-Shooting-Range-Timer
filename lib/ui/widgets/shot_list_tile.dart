/// Display classification of a detection event.
enum EventKind {
  /// Detected, unreviewed, normal confidence.
  detected('Detected', Tone.neutral, Icons.graphic_eq),

  /// The Detection Zone check could not decide; needs review.
  uncertain('Uncertain', Tone.warning, Icons.help_center_outlined),

  /// Detected but close to the confidence threshold.
  lowConfidence('Low confidence', Tone.warning, Icons.help_outline),

  /// Confirmed by the user.
  confirmed('Confirmed', Tone.accent, Icons.check_circle_outline),

  /// Rejected by the user (excluded from statistics).
  rejected('Rejected', Tone.error, Icons.block),

  /// Generated by simulation mode, not by the microphone.
  simulated('Simulated', Tone.info, Icons.science_outlined);

  const EventKind(this.label, this.tone, this.icon);
  final String label;
  final Tone tone;
  final IconData icon;
}

/// Margin above the session's threshold within which a detection is flagged
/// as low confidence.
const double kLowConfidenceMargin = 0.10;

/// Threshold assumed for sessions recorded before thresholds were stored.
const double kDefaultThresholdForReview = 0.70;

/// Classifies [shot] for display. Review state takes precedence over
/// confidence; simulated sessions are always labelled as such.
EventKind classifyEvent(
  ShotEvent shot, {
  double? threshold,
  bool simulated = false,
}) {
  switch (shot.reviewStatus) {
    case ReviewStatus.rejected:
      return EventKind.rejected;
    case ReviewStatus.confirmed:
      return EventKind.confirmed;
    case ReviewStatus.unreviewed:
      break;
  }
  if (simulated) return EventKind.simulated;
  if (shot.uncertain) return EventKind.uncertain;
  final double t = threshold ?? kDefaultThresholdForReview;
  if (shot.confidence < t + kLowConfidenceMargin) return EventKind.lowConfidence;
  return EventKind.detected;
}

/// One row in a detection timeline.
///
/// Shows the sequence number, elapsed timestamp, split from the previous
/// event, classifier confidence, estimated level, and review status. When
/// [onReview] is provided, confirm/reject controls are shown.
class DetectionEventItem extends StatelessWidget {
  final ShotEvent shot;

  /// Split from the previous event (or from the beep for the first event).
  final Duration? interval;

  /// Confidence threshold used for the session, if known.
  final double? threshold;

  /// Whether the event came from simulation mode.
  final bool simulated;

  /// Highlight as the newest live event.
  final bool isLatest;

  /// Called with the new status when the user confirms/rejects. Toggling an
  /// already-selected status returns the event to unreviewed.
  final ValueChanged<ReviewStatus>? onReview;

  /// Mark this split as the fastest in the session.
  final bool isFastest;

  const DetectionEventItem({
    super.key,
    required this.shot,
    this.interval,
    this.threshold,
    this.simulated = false,
    this.isLatest = false,
    this.onReview,
    this.isFastest = false,
  });

  @override
  Widget build(BuildContext context) {
    final EventKind kind =
        classifyEvent(shot, threshold: threshold, simulated: simulated);
    final bool rejected = kind == EventKind.rejected;
    final Color primaryText =
        rejected ? AppColors.textMuted : AppColors.textPrimary;

    final String elapsed = TimestampUtils.formatElapsed(shot.elapsedTime);
    final String split = interval == null ? '' : Fmt.split(interval!);

    return Semantics(
      container: true,
      label: 'Event ${shot.shotNumber}, at $elapsed'
          '${interval != null ? ', split $split' : ''}'
          ', confidence ${Fmt.percent(shot.confidence)}, ${kind.label}',
      child: Container(
        decoration: BoxDecoration(
          color: isLatest
              ? AppColors.tint(AppColors.accent, 0.06)
              : Colors.transparent,
          border: const Border(
            bottom: BorderSide(color: AppColors.border),
          ),
        ),
        padding: const EdgeInsets.symmetric(
            horizontal: AppSpace.lg, vertical: AppSpace.md),
        child: LayoutBuilder(
          builder: (context, constraints) {
            final bool wide = constraints.maxWidth >= 520;
            final Widget index = Container(
              width: 36,
              height: 36,
              alignment: Alignment.center,
              decoration: BoxDecoration(
                color: AppColors.surfaceElevated,
                borderRadius: AppRadius.smAll,
                border: Border.all(
                  color: isLatest ? AppColors.accent : AppColors.border,
                ),
              ),
              child: ExcludeSemantics(
                child: Text(
                  shot.shotNumber.toString().padLeft(2, '0'),
                  style: AppType.monoBody.copyWith(
                    color: isLatest ? AppColors.accent : primaryText,
                    fontWeight: FontWeight.w600,
                  ),
                ),
              ),
            );

            final Widget times = ExcludeSemantics(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                mainAxisSize: MainAxisSize.min,
                children: [
                  Text(
                    elapsed,
                    style: AppType.monoBody.copyWith(
                      fontSize: 16,
                      color: primaryText,
                      decoration: rejected ? TextDecoration.lineThrough : null,
                      decorationColor: AppColors.textMuted,
                    ),
                  ),
                  const SizedBox(height: 2),
                  Row(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      if (interval != null)
                        Text(
                          '+$split',
                          style: AppType.monoCaption.copyWith(
                            color: isFastest && !rejected
                                ? AppColors.accent
                                : AppColors.textSecondary,
                          ),
                        ),
                      if (isFastest && !rejected) ...[
                        const SizedBox(width: 6),
                        Text('FASTEST',
                            style: AppType.overline.copyWith(
                                fontSize: 9, color: AppColors.accent)),
                      ],
                    ],
                  ),
                ],
              ),
            );

            final Widget metrics = ExcludeSemantics(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.end,
                mainAxisSize: MainAxisSize.min,
                children: [
                  Text(Fmt.percent(shot.confidence),
                      style: AppType.monoBody.copyWith(color: primaryText)),
                  const SizedBox(height: 2),
                  Text('~${shot.peakDecibels.toStringAsFixed(0)} dB',
                      style: AppType.monoCaption),
                ],
              ),
            );

            final Widget tag =
                StatusTag(label: kind.label, tone: kind.tone, icon: kind.icon, dense: true);

            final Widget? review = onReview == null
                ? null
                : _ReviewButtons(status: shot.reviewStatus, onReview: onReview!);

            if (wide) {
              return Row(
                children: [
                  index,
                  const SizedBox(width: AppSpace.md),
                  Expanded(child: times),
                  SizedBox(width: 130, child: Align(alignment: Alignment.centerLeft, child: tag)),
                  const SizedBox(width: AppSpace.md),
                  SizedBox(width: 64, child: metrics),
                  if (review != null) ...[
                    const SizedBox(width: AppSpace.sm),
                    review,
                  ],
                ],
              );
            }
            return Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                Row(
                  children: [
                    index,
                    const SizedBox(width: AppSpace.md),
                    Expanded(child: times),
                    metrics,
                  ],
                ),
                const SizedBox(height: AppSpace.sm),
                Row(
                  children: [
                    const SizedBox(width: 48),
                    Flexible(child: tag),
                    const Spacer(),
                    if (review != null) review,
                  ],
                ),
              ],
            );
          },
        ),
      ),
    );
  }
}

class _ReviewButtons extends StatelessWidget {
  const _ReviewButtons({required this.status, required this.onReview});

  final ReviewStatus status;
  final ValueChanged<ReviewStatus> onReview;

  @override
  Widget build(BuildContext context) {
    final bool confirmed = status == ReviewStatus.confirmed;
    final bool rejected = status == ReviewStatus.rejected;
    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        IconButton(
          tooltip: confirmed ? 'Undo confirm' : 'Confirm as shot',
          isSelected: confirmed,
          onPressed: () => onReview(
              confirmed ? ReviewStatus.unreviewed : ReviewStatus.confirmed),
          icon: const Icon(Icons.check),
          selectedIcon: const Icon(Icons.check_circle),
          color: confirmed ? AppColors.accent : AppColors.textSecondary,
        ),
        IconButton(
          tooltip: rejected ? 'Undo reject' : 'Reject as false detection',
          isSelected: rejected,
          onPressed: () => onReview(
              rejected ? ReviewStatus.unreviewed : ReviewStatus.rejected),
          icon: const Icon(Icons.close),
          selectedIcon: const Icon(Icons.cancel),
          color: rejected ? AppColors.error : AppColors.textSecondary,
        ),
      ],
    );
  }
}

